use std::array;

use super::*;

/// Python's `hmac`: PRK = HMAC-SHA256(32 zero bytes, secret), then each secret is
/// HMAC-SHA256(PRK, label ‖ 0x01), the one block of 32 bytes; the secret is 0x00 to 0x1f. The
/// TLS seed is the one QUIC's endpoint derived from the same secret, so the key it gives does
/// not change.
#[test]
fn each_secret_is_an_independent_hkdfs() {
    let secret = ServerSecret::new(Secret::new(array::from_fn(|index| {
        u8::try_from(index).unwrap()
    })));
    let tls_seed = [
        0xef, 0xe4, 0x99, 0xab, 0xef, 0x5f, 0x22, 0x1c, 0x77, 0xa3, 0x57, 0x06, 0x1d, 0x5a, 0x76,
        0x34, 0x94, 0x8a, 0x37, 0xb0, 0x35, 0x3a, 0x59, 0xce, 0x30, 0xfd, 0xf9, 0xc0, 0x51, 0x63,
        0xc5, 0x31,
    ];
    let reset_key = [
        0x97, 0x7e, 0x2b, 0x60, 0xb4, 0xc2, 0xb7, 0x53, 0x36, 0x0e, 0x38, 0x87, 0xd8, 0xf4, 0x99,
        0x02, 0x94, 0xc7, 0x7f, 0x79, 0x64, 0x3a, 0xcd, 0xdc, 0x29, 0xb7, 0x95, 0xfb, 0x5d, 0x31,
        0xd1, 0xab,
    ];
    assert_eq!(DerivedSecret::TlsSeed.of(&secret).as_bytes(), &tls_seed);
    assert_eq!(DerivedSecret::ResetKey.of(&secret).as_bytes(), &reset_key);
}
